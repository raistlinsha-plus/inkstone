import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const dir = dirname(fileURLToPath(import.meta.url));
const css = "\n" + readFileSync(resolve(dir, "prototype.css"), "utf8") + "\n";
const concepts = Object.fromEntries(Object.entries({
  motuan: "motuan-concept.png", yanzhou: "yanzhou-concept.png",
  zhiwei: "zhiwei-concept.png", motuanScene: "motuan-study-concept.png",
}).map(([key,file]) => [key,"data:image/png;base64," + readFileSync(resolve(dir,"assets",file)).toString("base64")]));
const script = "\n" + readFileSync(resolve(dir,"prototype.js"),"utf8")
  .replace("/* EMBED_CONCEPT_ASSETS */ {}", JSON.stringify(concepts))
  .replace("/* EMBED_CHAT_MODULE */", readFileSync(resolve(dir,"chat.js"),"utf8")) + "\n";
if (/<\/(?:script|style)/i.test(css + script))
  throw Error("Inline source contains closing HTML tag");
const hash = (s) => createHash("sha256").update(s).digest("base64");
const policy =
  "default-src 'none'; script-src 'sha256-" +
  hash(script) +
  "'; style-src 'sha256-" +
  hash(css) +
  "'; img-src data:; connect-src 'none'; object-src 'none'; base-uri 'none'";
let html = readFileSync(resolve(dir, "index.template.html"), "utf8");
html = html
  .replace(
    /<meta\s+http-equiv="Content-Security-Policy"\s+content="[^"]*"\s*\/?>/i,
    '<meta http-equiv="Content-Security-Policy" content="' + policy + '">',
  )
  .replace(
    /<link\s+rel="stylesheet"\s+href="prototype.css"\s*\/?>/i,
    "<style>" + css + "</style>",
  )
  .replace(/<script\s+src="prototype.js"\s+defer\s*>\s*<\/script>/i, "")
  .replace(/\n[\t ]+(?=\n\s*<\/head>)/g, "\n")
  .replace("</body>", "<script>" + script + "</script>\n</body>");
if (/(?:href|src)="prototype\.(css|js)"/.test(html))
  throw Error("Portable build still has an external runtime asset");
writeFileSync(
  resolve(dir, "index.html"),
  "<!-- Generated by build.mjs; edit template/CSS/JS, then rebuild. -->\n" +
    html,
);
console.log(
  "Portable index.html rebuilt; embedded CSS/JS with hash-based CSP, no local fetch required.",
);
